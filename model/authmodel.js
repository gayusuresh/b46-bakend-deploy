const mongoose = require("mongoose");

const authSchema = mongoose.Schema({
  username: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    required: true,
    unique: true,
  },
  password: {
    type: String,
    required: true,
  },
  role: {
    type: String,
    required: true,
  },
});
const auth = mongoose.model("authusers", authSchema);

module.exports = auth;